"""Writes port/gen/resource_images.h: Freeserf's resource images (PNG) as
pixel arrays, since the Amiga port has no PNG decoder.

usage: python tools/embed_images.py freeserf/resources/button-advanced.png ...
Pixels are stored B, G, R, A as Freeserf's sprites keep them.
"""
import os
import sys

from PIL import Image


def main():
    out = []
    out.append("/* Generated by tools/embed_images.py - do not edit. */")
    out.append("#ifndef PORT_GEN_RESOURCE_IMAGES_H_")
    out.append("#define PORT_GEN_RESOURCE_IMAGES_H_")
    out.append("")
    out.append("#include <cstdint>")
    out.append("")
    out.append("struct ResourceImage {")
    out.append("  const char *name;")
    out.append("  unsigned int width, height;")
    out.append("  const uint8_t *bgra;")
    out.append("};")
    out.append("")
    names = []
    for i, path in enumerate(sys.argv[1:]):
        img = Image.open(path).convert("RGBA")
        w, h = img.size
        data = []
        for r, g, b, a in img.getdata():
            data += [b, g, r, a]
        var = "resource_image_%d" % i
        out.append("static const uint8_t %s[] = {" % var)
        for k in range(0, len(data), 16):
            out.append("  " + ", ".join(str(v) for v in data[k:k + 16]) + ",")
        out.append("};")
        names.append((os.path.basename(path), w, h, var))
    out.append("")
    out.append("static const ResourceImage resource_images[] = {")
    for name, w, h, var in names:
        out.append('  { "%s", %d, %d, %s },' % (name, w, h, var))
    out.append("};")
    out.append("")
    out.append("#endif  // PORT_GEN_RESOURCE_IMAGES_H_")
    path = os.path.join("port", "gen", "resource_images.h")
    open(path, "w", newline="\n").write("\n".join(out) + "\n")
    print("%s: %s" % (path, ", ".join("%s %dx%d" % n[:3] for n in names)))


if __name__ == "__main__":
    main()
